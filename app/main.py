from fastapi import FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from app.jira_client import fetch_done_tickets
from app.runbook_generator import generate_runbook, generate_all_runbooks
from app.confluence_client import create_confluence_page
import os
import json
from datetime import datetime

app = FastAPI(
    title="RunPilot API",
    description="Auto-generate runbooks from Jira incidents",
    version="0.1.0"
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_methods=["*"],
    allow_headers=["*"],
)

RUNBOOKS_DIR = "generated_runbooks"
os.makedirs(RUNBOOKS_DIR, exist_ok=True)


@app.get("/")
def root():
    return {"message": "Welcome to RunPilot API", "status": "running"}


@app.get("/tickets/{project_key}")
def get_tickets(project_key: str):
    try:
        tickets = fetch_done_tickets(project_key)
        return {"project": project_key, "count": len(tickets), "tickets": tickets}
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))


@app.post("/generate/{project_key}/{ticket_key}")
def generate_single_runbook(project_key: str, ticket_key: str):
    try:
        tickets = fetch_done_tickets(project_key)
        ticket = next((t for t in tickets if t["key"] == ticket_key), None)
        if not ticket:
            raise HTTPException(status_code=404, detail=f"Ticket {ticket_key} not found")
        runbook = generate_runbook(ticket)
        filename = f"{RUNBOOKS_DIR}/{ticket_key}.md"
        with open(filename, "w", encoding="utf-8") as f:
            f.write(f"# Runbook: {ticket['summary']}\n")
            f.write(f"Generated by RunPilot on {datetime.now().strftime('%Y-%m-%d %H:%M')}\n\n")
            f.write(runbook)
        return {
            "ticket_key":   ticket_key,
            "ticket_title": ticket["summary"],
            "runbook":      runbook,
            "saved_to":     filename
        }
    except HTTPException:
        raise
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))


@app.post("/generate-all/{project_key}")
def generate_all(project_key: str):
    try:
        tickets = fetch_done_tickets(project_key, max_results=5)
        incident_tickets = [
            t for t in tickets
            if any(word in t["summary"].lower()
            for word in ["down", "error", "crash", "fail", "exhausted", "leak", "issue", "outage"])
        ]
        if not incident_tickets:
            incident_tickets = tickets[:3]
        runbooks = generate_all_runbooks(incident_tickets)
        saved_files = []
        for rb in runbooks:
            filename = f"{RUNBOOKS_DIR}/{rb['ticket_key']}.md"
            with open(filename, "w", encoding="utf-8") as f:
                f.write(f"# Runbook: {rb['ticket_title']}\n")
                f.write(f"Generated by RunPilot on {datetime.now().strftime('%Y-%m-%d %H:%M')}\n\n")
                f.write(rb["runbook"])
            saved_files.append(filename)
        return {
            "project":       project_key,
            "generated":     len(runbooks),
            "saved_files":   saved_files,
            "runbooks":      runbooks
        }
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))
    
@app.post("/generate-and-sync/{project_key}/{ticket_key}")
def generate_and_sync(project_key: str, ticket_key: str):
    try:
        tickets = fetch_done_tickets(project_key)
        ticket = next((t for t in tickets if t["key"] == ticket_key), None)
        if not ticket:
            raise HTTPException(status_code=404, detail=f"Ticket {ticket_key} not found")
        print(f"Generating runbook for {ticket_key}...")
        runbook = generate_runbook(ticket)
        filename = f"{RUNBOOKS_DIR}/{ticket_key}.md"
        with open(filename, "w", encoding="utf-8") as f:
            f.write(f"# Runbook: {ticket['summary']}\n\n")
            f.write(runbook)
        print(f"Pushing to Confluence...")
        confluence_title = f"Runbook: {ticket['summary']} ({ticket_key})"
        confluence_result = create_confluence_page(confluence_title, runbook)
        return {
            "ticket_key":        ticket_key,
            "ticket_title":      ticket["summary"],
            "runbook":           runbook,
            "saved_to":          filename,
            "confluence_url":    confluence_result["url"],
            "confluence_page_id": confluence_result["page_id"]
        }
    except HTTPException:
        raise
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))